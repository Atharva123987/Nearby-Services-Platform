"""Alembic environment (async, asyncpg). URL comes from app settings / DATABASE_URL."""

from __future__ import annotations

import asyncio
from logging.config import fileConfig
from typing import Any

from sqlalchemy.engine import Connection
from sqlalchemy.ext.asyncio import create_async_engine

from alembic import context
from app import models  # noqa: F401 - registers tables on Base.metadata
from app.core.config import get_settings
from app.db.base import Base

config = context.config
if config.config_file_name is not None:
    fileConfig(config.config_file_name)

target_metadata = Base.metadata

# Tables owned by PostGIS (and its optional extensions) must never be autogenerated/dropped.
_POSTGIS_TABLES = {"spatial_ref_sys", "geography_columns", "geometry_columns"}
_POSTGIS_SCHEMAS = {"tiger", "tiger_data", "topology"}


def _include_object(obj: Any, name: str | None, type_: str, reflected: bool, _: Any) -> bool:
    if type_ == "table" and reflected:
        return name not in _POSTGIS_TABLES and getattr(obj, "schema", None) not in _POSTGIS_SCHEMAS
    return True


def _database_url() -> str:
    return config.get_main_option("sqlalchemy.url") or get_settings().database_url


def run_migrations_offline() -> None:
    context.configure(
        url=_database_url(),
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
        include_object=_include_object,
    )
    with context.begin_transaction():
        context.run_migrations()


def _run_sync(connection: Connection) -> None:
    context.configure(
        connection=connection,
        target_metadata=target_metadata,
        include_object=_include_object,
        compare_type=True,
    )
    with context.begin_transaction():
        context.run_migrations()


async def run_migrations_online() -> None:
    engine = create_async_engine(_database_url())
    async with engine.connect() as connection:
        await connection.run_sync(_run_sync)
    await engine.dispose()


if context.is_offline_mode():
    run_migrations_offline()
else:
    asyncio.run(run_migrations_online())
